"""Server-side rules applied to every Gemma 4 answer before a patient sees it.

- A confidence level is shown only when the verified reference data covers the
  patient's condition. Otherwise it is left out and a specialist referral is required.
- Unclear images lower confidence; non-medical images get no medical reading.
- Every answer carries a referral to the kind of doctor who treats the problem.
"""

from __future__ import annotations

from .body_parts import BODY_PARTS, SPECIALISTS, body_part_label, default_specialist

LEVELS = ["low", "moderate", "high"]
URGENCIES = ["routine", "soon", "urgent", "emergency"]

DISCLAIMER = (
    "This explanation was generated by an AI model (Gemma 4) and compared with verified reference cases "
    "to help you understand your image. It is not a diagnosis. Your doctor and the radiologist's official "
    "report have the final word."
)
EMERGENCY_NOTICE = (
    "This may need care today. If you have severe pain, trouble breathing, chest pain, heavy bleeding, "
    "weakness or numbness, call 911 or go to the nearest emergency room now."
)
URGENT_NOTICE = "Contact a doctor within the next day or two to go over this image."
TIMEFRAMES = {
    "emergency": "Today - go to the emergency department",
    "urgent": "Within 1-2 days",
    "soon": "Within the next 1-2 weeks",
    "routine": "At your next routine visit",
}


def _cap(level: str, cap: str) -> str:
    level = level if level in LEVELS else "low"
    return LEVELS[min(LEVELS.index(level), LEVELS.index(cap))]


def _str(value, limit: int = 600) -> str:
    return " ".join(str(value or "").split())[:limit]


def _str_list(value, max_items: int, limit: int = 300) -> list[str]:
    if not isinstance(value, list):
        return []
    return [s for s in (_str(v, limit) for v in value) if s][:max_items]


def _mentions_other_body_part(detected: str, expected: str) -> bool:
    """True when Gemma clearly names a different body part than the patient selected."""
    d = detected.lower()
    if not d or expected == "whole_body":
        return False
    names = {key: [info["label"].lower().split(" ")[0], *info["synonyms"]] for key, info in BODY_PARTS.items()
             if key != "whole_body"}
    if any(n in d for n in names.get(expected, [])):
        return False
    return any(any(n in d for n in syns) for key, syns in names.items() if key != expected)


def _is_normal(condition: str) -> bool:
    c = condition.lower()
    return not c or any(w in c for w in ("normal", "no abnormal", "no acute", "no fracture", "unremarkable", "none"))


def finalize(raw: dict, *, body_part: str, modality: str, references_used: int) -> dict:
    """Clean up Gemma's JSON and apply the confidence, referral and urgency rules."""
    notes: list[str] = []
    cap = "high"

    is_medical = bool(raw.get("is_medical_image", True))
    quality = raw.get("image_quality") if raw.get("image_quality") in ("good", "limited", "unreadable") else "limited"
    detected = _str(raw.get("detected_body_part"), 80)
    condition = _str(raw.get("primary_condition"), 120)

    if not is_medical:
        cap = "low"
        notes.append("This doesn't look like an X-ray, MRI or CT image, so no medical reading was given.")
    if quality == "unreadable":
        cap = "low"
        notes.append("The image was too unclear to read reliably. Try a sharper, uncropped image.")
    elif quality == "limited":
        cap = _cap(cap, "moderate")
        notes.append("Image quality is limited, so confidence was lowered.")
    if detected and _mentions_other_body_part(detected, body_part):
        cap = _cap(cap, "moderate")
        notes.append(f"The image may show a different body part ({detected}) than the one selected.")

    supported = (
        is_medical
        and quality != "unreadable"
        and references_used > 0
        and bool(raw.get("condition_in_reference_data", False))
    )
    if not supported and is_medical:
        if references_used == 0:
            notes.append(f"There is no verified reference data for {body_part_label(body_part).lower()} yet.")
        notes.append("This condition isn't well covered by our verified reference data, so no confidence level is shown.")

    findings = []
    if is_medical:
        for f in (raw.get("findings") or [])[:5]:
            if not isinstance(f, dict) or not _str(f.get("finding")):
                continue
            backed = supported and bool(f.get("supported_by_reference_data", False))
            findings.append(
                {
                    "finding": _str(f.get("finding"), 160),
                    "location": _str(f.get("location"), 120),
                    "explanation": _str(f.get("explanation"), 500),
                    "supported_by_reference_data": backed,
                    "confidence": _cap(str(f.get("confidence", "low")), cap) if backed else None,
                }
            )

    urgency = raw.get("urgency") if raw.get("urgency") in URGENCIES else "soon"
    if not is_medical:
        urgency = "routine"

    # Referral: Gemma's pick if it's a known specialist, otherwise the usual one for the body part.
    ref = raw.get("referral") if isinstance(raw.get("referral"), dict) else {}
    specialist = ref.get("specialist") if ref.get("specialist") in SPECIALISTS else None
    if urgency == "emergency":
        specialist = "Emergency department"
    elif specialist is None:
        specialist = "Primary care doctor" if (supported and _is_normal(condition)) else default_specialist(body_part)
    referral = {
        "specialist": specialist,
        "reason": _str(ref.get("reason"), 300)
        or f"A {specialist.split(' (')[0].lower()} usually looks after problems in the {body_part_label(body_part).lower()}.",
        "timeframe": _str(ref.get("timeframe"), 80) or TIMEFRAMES[urgency],
        "required": (not supported) or urgency in ("urgent", "emergency") or not _is_normal(condition),
    }

    summary = _str(raw.get("summary"), 1200)
    if not is_medical:
        summary = (
            "This image doesn't appear to be an X-ray, MRI or CT scan, so it can't be read. "
            "Please upload the medical image itself (for example, exported from your patient portal)."
        )
        referral.update(specialist="Primary care doctor", required=False, timeframe=TIMEFRAMES["routine"])

    next_steps = _str_list(raw.get("next_steps"), 4)
    see = f"See a {referral['specialist'].split(' (')[0].lower()} ({referral['timeframe'].lower()})."
    if referral["required"] and not any(referral["specialist"].split(" (")[0].lower() in s.lower() for s in next_steps):
        next_steps.insert(0, see)
    if not any("radiolog" in s.lower() or "report" in s.lower() for s in next_steps):
        next_steps.append("Ask for the radiologist's official report on this image.")

    return {
        "is_medical_image": is_medical,
        "detected_body_part": detected,
        "image_quality": quality,
        "primary_condition": condition,
        "condition_in_reference_data": supported,
        "summary": summary,
        "findings": findings,
        "overall_confidence": _cap(str(raw.get("overall_confidence", "low")), cap) if supported else None,
        "confidence_reason": _str(raw.get("confidence_reason"), 400)
        if supported
        else f"Not given: this isn't well covered by our verified data. Please see a {referral['specialist'].split(' (')[0].lower()}.",
        "urgency": urgency,
        "urgency_notice": EMERGENCY_NOTICE if urgency == "emergency" else URGENT_NOTICE if urgency == "urgent" else None,
        "referral": referral,
        "reference_comparison": _str(raw.get("reference_comparison"), 500),
        "next_steps": next_steps[:5],
        "questions_for_doctor": _str_list(raw.get("questions_for_doctor"), 4),
        "safety_notes": notes,
        "disclaimer": DISCLAIMER,
    }
